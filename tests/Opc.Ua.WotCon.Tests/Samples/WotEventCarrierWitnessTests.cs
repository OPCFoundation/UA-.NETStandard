using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using NUnit.Framework;
using Opc.Ua.Export;
using Opc.Ua.Wot;

namespace Opc.Ua.WotCon.Tests.Samples
{
    /// <summary>
    /// Under <c>WhenRequired</c> the four sample-pump event carriers are legitimately plain readable
    /// EventType documents: they reconstruct their EventType, so only 104 of the 108 pump nodes are
    /// preserved natively. A resource that names such an event is valid when the event identity is
    /// generated by its own root's TypeDefinition chain through a native GeneratesEvent reference.
    /// An event of another owner, a tampered root identity and a carrier that states a different
    /// identity than the event that links to it must still be rejected.
    /// </summary>
    [TestFixture]
    [Category("WoT")]
    public sealed class WotEventCarrierWitnessTests
    {
        private const string Prefix = "nsu=urn:opcfoundation.org:UA:WotAggregation:PumpInstance;s=";
        private const string Root = "sample-pump";
        private const string CavitationCarrier = "sample-pump-cavitationalarm";
        private const string CavitationId = "\"uav:id\": \"" + Prefix + "Pump1.CavitationAlarm\"";
        private const string OverheatId = "\"uav:id\": \"" + Prefix + "Pump1.MotorOverheatAlarm\"";
        private const string RootId = "\"uav:id\": \"" + Prefix + "Pump1\",";

        /// <summary>
        /// The published root converts successfully with its carriers served, restores its event
        /// identities through the owning type's native GeneratesEvent references and fabricates no
        /// EventType that no preserved node supports.
        /// </summary>
        [Test]
        public async Task WitnessedReadableEventCarrierConvertsPerResourceAsync()
        {
            Dictionary<string, byte[]> corpus = ReadCorpus();
            string rootText = Encoding.UTF8.GetString(corpus[Root]);
            Assert.That(rootText, Does.Contain(CavitationId));
            Assert.That(rootText, Does.Contain(OverheatId));

            WotConversionResult<UANodeSet> result = await ConvertAsync(corpus[Root], corpus, corpus)
                .ConfigureAwait(false);

            UANodeSet context = FindContext(corpus);
            using IDisposable scope = Assert.EnterMultipleScope();
            Assert.That(
                result.Success,
                Is.True,
                string.Join("; ", result.Diagnostics.Select(d => d.ToString())));
            Assert.That(result.Value, Is.Not.Null);
            foreach (string id in new[] { "Pump1.CavitationAlarm", "Pump1.MotorOverheatAlarm" })
            {
                Assert.That(GeneratesEventTargets(context), Does.Contain(id), "context " + id);
                Assert.That(Ids(context), Does.Not.Contain(id), "native " + id);
                Assert.That(Ids(result.Value!), Does.Not.Contain(id), "fabricated " + id);
            }
        }

        /// <summary>
        /// A tampered root identity, an event of another owner and an event no owner generates
        /// still conflict with the authoritative preserved facts.
        /// </summary>
        [TestCase(RootId, "\"uav:id\": \"" + Prefix + "Pump9\",")]
        [TestCase(CavitationId, "\"uav:id\": \"" + Prefix + "Pump2.CavitationAlarm\"")]
        [TestCase(OverheatId, "\"uav:id\": \"" + Prefix + "Pump1.OtherAlarm\"")]
        public async Task TamperedRootOrEventIdentityConflictsAsync(string original, string tampered)
        {
            Dictionary<string, byte[]> corpus = ReadCorpus();
            string rootText = Encoding.UTF8.GetString(corpus[Root]);
            Assert.That(rootText, Does.Contain(original));
            byte[] tamperedRoot = Encoding.UTF8.GetBytes(
                rootText.Replace(original, tampered, StringComparison.Ordinal));

            WotConversionResult<UANodeSet> result = await ConvertAsync(tamperedRoot, corpus, corpus)
                .ConfigureAwait(false);

            Assert.That(
                result.Diagnostics.Any(d => d.Code == WotDiagnosticCode.NativeProjectionConflict),
                Is.True,
                string.Join("; ", result.Diagnostics.Select(d => d.ToString())));
        }

        /// <summary>
        /// A readable carrier that states another identity than the event that links to it is not
        /// accepted just because the event itself is witnessed natively.
        /// </summary>
        [Test]
        public async Task CarrierStatingAnotherIdentityIsRejectedAsync()
        {
            Dictionary<string, byte[]> corpus = ReadCorpus();
            var served = new Dictionary<string, byte[]>(corpus, StringComparer.Ordinal);
            string carrier = Encoding.UTF8.GetString(corpus[CavitationCarrier]);
            Assert.That(carrier, Does.Contain(CavitationId));
            served[CavitationCarrier] = Encoding.UTF8.GetBytes(carrier.Replace(
                CavitationId,
                "\"uav:id\": \"" + Prefix + "Pump2.CavitationAlarm\"",
                StringComparison.Ordinal));

            WotConversionResult<UANodeSet> result = await ConvertAsync(corpus[Root], corpus, served)
                .ConfigureAwait(false);

            Assert.That(
                result.Success,
                Is.False,
                "The served carrier states another identity; the conversion must not report success.");
            Assert.That(
                result.Diagnostics.Any(d => d.ToString().Contains(
                    "Pump2.CavitationAlarm",
                    StringComparison.Ordinal)),
                Is.True,
                "A diagnostic must name the identity the carrier states: "
                + string.Join("; ", result.Diagnostics.Select(d => d.ToString())));
        }

        /// <summary>
        /// The public <c>WhenRequired</c> export of the sample pump keeps 104 preserved nodes and four
        /// readable event carriers, restores the complete source, and every native resource validates
        /// against the context of the others without any native payload being forced onto a carrier.
        /// </summary>
        [Test]
        public async Task WhenRequiredExportRoundTripsAndEveryResourceValidatesAsync()
        {
            string sourcePath = Path.Combine(DocumentsDirectory(), "SamplePump.NodeSet2.xml");
            UANodeSet source = WotAggregationDocumentGenerator.ReadNodeSet(sourcePath);
            WotNodeSetConverterOptions options = WotAggregationDocumentGenerator.CreateLargeDocumentOptions();
            options.PreservationMode = WotNodeSetPreservationMode.WhenRequired;

            WotConversionResult<WotDocumentSet> exported = await WotNodeSetConverter
                .FromNodeSetDocumentsAsync(source, Root, null, options).ConfigureAwait(false);
            Assert.That(exported.Success, Is.True, string.Join("; ", exported.Diagnostics));
            using WotDocumentSet set = exported.Value!;

            WotDocumentSetEntry[] entries = [.. set.Entries.ToList()];
            WotDocumentSetEntry[] natives = [.. entries.Where(entry => NativeNodeCount(entry.Document) > 0)];
            string[] carrierIds = [.. entries
                .Where(entry => NativeNodeCount(entry.Document) == 0 && IsEventCarrier(entry.Document))
                .Select(entry => entry.Document.RootElement.GetProperty("uav:id").GetString()!)];
            WotConversionResult<UANodeSet> restored = await WotNodeSetConverter.ToNodeSetAsync(set, options)
                .ConfigureAwait(false);

            using IDisposable scope = Assert.EnterMultipleScope();
            Assert.That(natives.Sum(entry => NativeNodeCount(entry.Document)), Is.EqualTo(104));
            Assert.That(
                carrierIds,
                Is.EquivalentTo(new[]
                {
                    Prefix + "Pump1.CavitationAlarm",
                    Prefix + "Pump1.MotorOverheatAlarm",
                    Prefix + "Pump2.CavitationAlarm",
                    Prefix + "Pump2.MotorOverheatAlarm"
                }));
            Assert.That(restored.Success, Is.True, string.Join("; ", restored.Diagnostics));
            Assert.That(source.Items?.Length, Is.EqualTo(108));
            Assert.That(restored.Value!.Items?.Length, Is.EqualTo(108));
            Assert.That(
                WotNodeSetConverter.CompareDocumentSet(source, restored.Value!, options).AreEquivalent,
                Is.True);

            var contexts = new WotNodeSetConverter.ArchiveContextIndex(options);
            var served = new Dictionary<string, byte[]>(StringComparer.Ordinal);
            foreach (WotDocumentSetEntry entry in entries)
            {
                contexts.Add(entry.Document);
                served[Normalize(entry.Href)] = entry.Document.Utf8Json.ToArray();
            }
            foreach (WotDocumentSetEntry entry in natives)
            {
                WotConversionResult<UANodeSet> resource = await WotNodeSetConverter.ToNodeSetResultAsync(
                    entry.Document, options, new CorpusResolver(served, contexts)).ConfigureAwait(false);
                Assert.That(
                    resource.Success,
                    Is.True,
                    entry.Href + ": " + string.Join("; ", resource.Diagnostics.Select(d => d.ToString())));
            }
        }

        private static async Task<WotConversionResult<UANodeSet>> ConvertAsync(
            byte[] target,
            Dictionary<string, byte[]> indexed,
            Dictionary<string, byte[]> served)
        {
            WotNodeSetConverterOptions options = WotAggregationDocumentGenerator.CreateLargeDocumentOptions();
            var contexts = new WotNodeSetConverter.ArchiveContextIndex(options);
            foreach (byte[] bytes in indexed.Values)
            {
                using WotDocument sibling = WotDocument.Parse(bytes, options);
                contexts.Add(sibling);
            }

            using WotDocument document = WotDocument.Parse(target, options);
            return await WotNodeSetConverter
                .ToNodeSetResultAsync(document, options, new CorpusResolver(served, contexts))
                .ConfigureAwait(false);
        }

        private static UANodeSet FindContext(Dictionary<string, byte[]> corpus)
        {
            WotNodeSetConverterOptions options = WotAggregationDocumentGenerator.CreateLargeDocumentOptions();
            var contexts = new WotNodeSetConverter.ArchiveContextIndex(options);
            foreach (byte[] bytes in corpus.Values)
            {
                using WotDocument sibling = WotDocument.Parse(bytes, options);
                contexts.Add(sibling);
            }
            using WotDocument root = WotDocument.Parse(corpus[Root], options);
            return contexts.Find(root) ?? throw new InvalidOperationException("The root has no archive context.");
        }

        private static IEnumerable<string> Ids(UANodeSet nodeSet)
        {
            return (nodeSet.Items ?? []).Select(node => Tail(node.NodeId));
        }

        private static string Tail(string? id)
        {
            string value = id ?? string.Empty;
            int index = value.StartsWith("s=", StringComparison.Ordinal)
                ? 0
                : value.IndexOf(";s=", StringComparison.Ordinal) + 1;
            return index <= 0 && !value.StartsWith("s=", StringComparison.Ordinal) ? value : value[(index + 2)..];
        }

        private static IEnumerable<string> GeneratesEventTargets(UANodeSet nodeSet)
        {
            return (nodeSet.Items ?? [])
                .SelectMany(node => node.References ?? [])
                .Where(reference => reference.IsForward &&
                    reference.ReferenceType is "i=41" or "GeneratesEvent")
                .Select(reference => Tail(reference.Value));
        }

        private static int NativeNodeCount(WotDocument document)
        {
            return document.RootElement.TryGetProperty("uav:nodes", out JsonElement native) &&
                native.TryGetProperty("nodes", out JsonElement nodes)
                ? nodes.GetArrayLength()
                : 0;
        }

        private static bool IsEventCarrier(WotDocument document)
        {
            return document.RootElement.TryGetProperty("@type", out JsonElement type) &&
                type.ValueKind == JsonValueKind.Array &&
                type.EnumerateArray().Any(item => item.GetString() == "uav:eventType");
        }

        private static string Normalize(string reference)
        {
            int fragment = reference.IndexOf('#', StringComparison.Ordinal);
            string href = fragment < 0 ? reference : reference[..fragment];
            href = href.StartsWith("./", StringComparison.Ordinal) ? href[2..] : href;
            href = href.EndsWith(".json", StringComparison.Ordinal) ? href[..^5] : href;
            return href[(href.LastIndexOf('/') + 1)..];
        }

        private static Dictionary<string, byte[]> ReadCorpus()
        {
            string directory = Path.Combine(DocumentsDirectory(), "sample-pump");
            return Directory.GetFiles(directory, "*.json").ToDictionary(
                path => Path.GetFileNameWithoutExtension(path),
                path => File.ReadAllBytes(path),
                StringComparer.Ordinal);
        }

        private static string DocumentsDirectory()
        {
            DirectoryInfo? directory = new(TestContext.CurrentContext.TestDirectory);
            while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "UA.slnx")))
            {
                directory = directory.Parent;
            }
            return Path.Combine(
                directory?.FullName ?? throw new DirectoryNotFoundException("Could not locate the repository root."),
                "samples", "WotCon", "AggregationClient", "Documents");
        }

        /// <summary>
        /// A resolver that serves the corpus documents and supplies a native archive context.
        /// </summary>
        private sealed class CorpusResolver : IWotThingResolver, IWotArchiveContextProvider
        {
            /// <summary>
            /// Creates the resolver over the corpus documents and a context index.
            /// </summary>
            /// <param name="documents">The corpus documents keyed by normalized reference.</param>
            /// <param name="contexts">The index that supplies the native contexts.</param>
            public CorpusResolver(
                Dictionary<string, byte[]> documents,
                WotNodeSetConverter.ArchiveContextIndex contexts)
            {
                m_documents = documents;
                m_contexts = contexts;
            }

            /// <inheritdoc/>
            public UANodeSet? GetArchiveContext(WotDocument document)
            {
                return m_contexts.Find(document);
            }

            /// <inheritdoc/>
            public ValueTask<WotResolverResult> ResolveThingAsync(
                string reference,
                WotResolutionContext context,
                CancellationToken cancellationToken)
            {
                cancellationToken.ThrowIfCancellationRequested();
                return new ValueTask<WotResolverResult>(
                    m_documents.TryGetValue(Normalize(reference), out byte[]? bytes)
                        ? WotResolverResult.FromBytes(bytes)
                        : WotResolverResult.NotFound);
            }

            private readonly Dictionary<string, byte[]> m_documents;
            private readonly WotNodeSetConverter.ArchiveContextIndex m_contexts;
        }
    }
