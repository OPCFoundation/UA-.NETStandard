using System;
using System.Threading;
using System.Threading.Tasks;

namespace Opc.Ua.GranulateDrying.Client
{
    /// <summary>
    /// A typed value that retains absence, source quality, and both UA timestamps.
    /// A default typed value is not a measurement unless HasValue is true.
    /// </summary>
    /// <typeparam name="T">The exact declared CLR data type.</typeparam>
    /// <param name="NodeId">The resolved variable, or NodeId.Null for an absent optional member.</param>
    /// <param name="DataValue">The original UA result, without discarding its status or timestamps.</param>
    /// <param name="Value">The decoded value when HasValue is true.</param>
    /// <param name="HasValue">Whether the payload can be decoded as T.</param>
    public sealed record GranulateDryingReading<T>(NodeId NodeId, DataValue DataValue, T Value, bool HasValue)
    {
        /// <summary>
        /// Gets whether the server exposes this optional variable.
        /// </summary>
        public bool IsPresent => !NodeId.IsNull;
    }

    /// <summary>
    /// A namespace-URI-qualified typed standard variable.
    /// Generated object proxies handle methods; this module covers variable access not generated by the pipeline.
    /// </summary>
    /// <typeparam name="T">The exact declared CLR data type.</typeparam>
    public sealed class GranulateDryingVariable<T>
    {
        /// <summary>
        /// Creates a typed standard variable path.
        /// </summary>
        internal GranulateDryingVariable(
            GranulateDryingClientContext context,
            NodeId owner,
            ArrayOf<GranulateDryingPathElement> path,
            GranulateDryingCodec<T> codec,
            bool writable)
        {
            m_context = context;
            m_owner = owner;
            m_path = path;
            m_codec = codec;
            IsWritable = writable;
        }

        /// <summary>
        /// Gets whether the companion model declares this member writable.
        /// User permissions and remote-control ownership are still enforced by the server.
        /// </summary>
        public bool IsWritable { get; }

        /// <summary>
        /// Resolves the variable using current namespace indices rather than assuming numeric indices.
        /// </summary>
        public ValueTask<NodeId> ResolveAsync(CancellationToken cancellationToken = default)
        {
            return m_context.ResolveAsync(m_owner, m_path, cancellationToken);
        }

        /// <summary>
        /// Reads a typed value without treating an absent optional member as zero or a bad value as good.
        /// </summary>
        public async ValueTask<GranulateDryingReading<T>> ReadAsync(CancellationToken cancellationToken = default)
        {
            NodeId node = await ResolveAsync(cancellationToken).ConfigureAwait(false);
            if (node.IsNull)
            {
                return new GranulateDryingReading<T>(NodeId.Null,
                    DataValue.FromStatusCode(StatusCodes.BadNotSupported), default!, false);
            }
            ReadResponse response = await m_context.Session.ReadAsync(
                null, 0, TimestampsToReturn.Both,
                [new ReadValueId { NodeId = node, AttributeId = Attributes.Value }],
                cancellationToken).ConfigureAwait(false);
            if (response.Results.Count != 1)
            {
                throw new ServiceResultException(StatusCodes.BadUnexpectedError);
            }
            DataValue value = response.Results[0];
            bool decoded = m_codec.Decode(value.WrappedValue, out T typed);
            if (!decoded && StatusCode.IsGood(value.StatusCode) && !value.WrappedValue.IsNull)
            {
                throw ServiceResultException.Create(
                    StatusCodes.BadTypeMismatch, "The server returned a different type for '{0}'.", node);
            }
            return new GranulateDryingReading<T>(node, value, typed, decoded);
        }

        /// <summary>
        /// Writes an exact typed value and returns the server's successful status, including GoodClamped.
        /// Bad responses and absent optional members raise ServiceResultException.
        /// </summary>
        public async ValueTask<StatusCode> WriteAsync(T value, CancellationToken cancellationToken = default)
        {
            if (!IsWritable)
            {
                throw new ServiceResultException(StatusCodes.BadNotWritable);
            }
            NodeId node = await ResolveAsync(cancellationToken).ConfigureAwait(false);
            if (node.IsNull)
            {
                throw new ServiceResultException(StatusCodes.BadNotSupported);
            }
            WriteResponse response = await m_context.Session.WriteAsync(null,
                [new WriteValue
                {
                    NodeId = node,
                    AttributeId = Attributes.Value,
                    Value = new DataValue(m_codec.Encode(value))
                }], cancellationToken).ConfigureAwait(false);
            if (response.Results.Count != 1)
            {
                throw new ServiceResultException(StatusCodes.BadUnexpectedError);
            }
            StatusCode status = response.Results[0];
            if (StatusCode.IsBad(status))
            {
                throw new ServiceResultException(status);
            }
            return status;
        }

        /// <summary>
        /// Reads the exact EngineeringUnits property when this variable is analog.
        /// </summary>
        public ValueTask<GranulateDryingReading<EUInformation>> ReadEngineeringUnitsAsync(
            CancellationToken cancellationToken = default)
        {
            return new GranulateDryingVariable<EUInformation>(
                m_context, m_owner,
                m_path + new GranulateDryingPathElement(Opc.Ua.Namespaces.OpcUa, Opc.Ua.BrowseNames.EngineeringUnits),
                GranulateDryingCodecs.Structure<EUInformation>(), false).ReadAsync(cancellationToken);
        }

        /// <summary>
        /// Reads the declared engineering range without inventing a device operating envelope.
        /// </summary>
        public ValueTask<GranulateDryingReading<Range>> ReadRangeAsync(CancellationToken cancellationToken = default)
        {
            return new GranulateDryingVariable<Range>(
                m_context, m_owner,
                m_path + new GranulateDryingPathElement(Opc.Ua.Namespaces.OpcUa, Opc.Ua.BrowseNames.EURange),
                GranulateDryingCodecs.Structure<Range>(), false).ReadAsync(cancellationToken);
        }

        /// <summary>
        /// The connected-session module.
        /// </summary>
        private readonly GranulateDryingClientContext m_context;

        /// <summary>
        /// The root of the variable path.
        /// </summary>
        private readonly NodeId m_owner;

        /// <summary>
        /// The standard URI-qualified path.
        /// </summary>
        private readonly ArrayOf<GranulateDryingPathElement> m_path;

        /// <summary>
        /// NativeAOT-safe typed conversion functions.
        /// </summary>
        private readonly GranulateDryingCodec<T> m_codec;
    }

    /// <summary>
    /// A standard browse-path segment identified by namespace URI.
    /// </summary>
    internal readonly record struct GranulateDryingPathElement(string NamespaceUri, string Name);

    /// <summary>
    /// Decodes one known wire type without object boxing or runtime reflection.
    /// </summary>
    /// <typeparam name="T">The declared variable value type.</typeparam>
    internal delegate bool GranulateDryingDecoder<T>(Variant value, out T result);

    /// <summary>
    /// Typed value conversion functions selected statically by each public accessor.
    /// </summary>
    /// <typeparam name="T">The declared variable value type.</typeparam>
    internal sealed record GranulateDryingCodec<T>(
        Func<T, Variant> Encode,
        GranulateDryingDecoder<T> Decode);

    /// <summary>
    /// Statically selected codecs for the GDD model's variable types.
    /// </summary>
    internal static class GranulateDryingCodecs
    {
        /// <summary>
        /// The Boolean codec.
        /// </summary>
        internal static GranulateDryingCodec<bool> Boolean { get; } = new(
            Variant.From, static (Variant value, out bool result) => value.TryGetValue(out result));

        /// <summary>
        /// The Byte codec.
        /// </summary>
        internal static GranulateDryingCodec<byte> Byte { get; } = new(
            Variant.From, static (Variant value, out byte result) => value.TryGetValue(out result));

        /// <summary>
        /// The UInt16 codec.
        /// </summary>
        internal static GranulateDryingCodec<ushort> UInt16 { get; } = new(
            Variant.From, static (Variant value, out ushort result) => value.TryGetValue(out result));

        /// <summary>
        /// The UInt32 codec.
        /// </summary>
        internal static GranulateDryingCodec<uint> UInt32 { get; } = new(
            Variant.From, static (Variant value, out uint result) => value.TryGetValue(out result));

        /// <summary>
        /// The Double and UA Duration codec.
        /// </summary>
        internal static GranulateDryingCodec<double> Double { get; } = new(
            Variant.From, static (Variant value, out double result) => value.TryGetValue(out result));

        /// <summary>
        /// The String and LocaleId codec.
        /// </summary>
        internal static GranulateDryingCodec<string> String { get; } = new(
            Variant.From, static (Variant value, out string result) => value.TryGetValue(out result));

        /// <summary>
        /// The UtcTime codec.
        /// </summary>
        internal static GranulateDryingCodec<DateTimeUtc> Time { get; } = new(
            Variant.From, static (Variant value, out DateTimeUtc result) => value.TryGetValue(out result));

        /// <summary>
        /// The LocalizedText codec.
        /// </summary>
        internal static GranulateDryingCodec<LocalizedText> Text { get; } = new(
            Variant.From, static (Variant value, out LocalizedText result) => value.TryGetValue(out result));

        /// <summary>
        /// Creates a statically closed generated-enumeration codec.
        /// </summary>
        /// <typeparam name="T">The generated enumeration type.</typeparam>
        internal static GranulateDryingCodec<T> Enumeration<T>() where T : struct, Enum
        {
            return new GranulateDryingCodec<T>(
                Variant.From, static (Variant value, out T result) => value.TryGetValue(out result));
        }

        /// <summary>
        /// Creates a generated structure codec.
        /// </summary>
        /// <typeparam name="T">The generated structure type.</typeparam>
        internal static GranulateDryingCodec<T> Structure<T>() where T : class, IEncodeable
        {
            return new GranulateDryingCodec<T>(
                static value => Variant.FromStructure(value),
                static (Variant value, out T result) =>
                {
                    bool decoded = value.TryGetStructure<T>(out T? parsed);
                    result = parsed!;
                    return decoded;
                });
        }

        /// <summary>
        /// Creates a generated structure-array codec.
        /// </summary>
        /// <typeparam name="T">The generated structure element type.</typeparam>
        internal static GranulateDryingCodec<ArrayOf<T>> Structures<T>() where T : class, IEncodeable
        {
            return new GranulateDryingCodec<ArrayOf<T>>(
                static value => Variant.FromStructure(value),
                static (Variant value, out ArrayOf<T> result) => value.TryGetStructure(out result));
        }
    }
}
